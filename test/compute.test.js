'use strict';
const assert=require('node:assert/strict');
const {testDb}=require('./helpers/db');
const {createBroker}=require('../server/compute/broker');
const {loadCompute}=require('../server/compute/config');
(async()=>{
 const t=await testDb(); let time=Date.UTC(2026,10,8); let created=0,removed=0,deleted=false,uncertain=false;
 const q={provider:'hetzner',id:'cx',hourly:1,currency:'EUR',ram_mb:4096,gpu_mb:0,tier:'dedicated',region:'eu',setup:0,billing_seconds:3600,expires_at:time+60000};
 const config={compute:{enabled:true,dry_run:false,owner:'alice',pools:{browsers:{kind:'browser',currency:'EUR',providers:['hetzner'],min_warm:1,strategy:'automatic'}},inventory:{m:{pool:'browsers',tier:'dedicated',ram_mb:4096,hourly:1,currency:'EUR'}},providers:{hetzner:{key:'stub',monthly_cap:'2',currency:'EUR',image:'prepared',costs_bounded:true,extra_hourly:'0'}}}};
 const adapters={hetzner:{quote:async()=>[q],provision:async()=>{created++;if(uncertain)throw new Error('timeout');return {id:'remote'};},health:async()=>({deleted,state:'running'}),release:async()=>{removed++;}}};
 const desks={enabled:true,hosts:async()=>[{machine_id:'m',trust:'first-party',online:true,free:4,max_browser_desks:4}]};
 let broker=createBroker({db:t.db,config,desks,adapters,now:()=>time});
 try {
  assert.equal(loadCompute({}).dry_run,true);assert.equal(loadCompute({}).providers.hetzner.monthly_cap,'0');
  config.compute.providers.hetzner.monthly_cap='0';
  assert.match((await broker.provision('browsers',q)).reason,/quote only/);assert.equal(created,0);
  config.compute.providers.hetzner.monthly_cap='2';
  config.compute.dry_run=true;assert.equal((await broker.provision('browsers',q)).dry_run,true);assert.equal(created,0);
  config.compute.dry_run=false;
  const results=await Promise.all([broker.provision('browsers',q),broker.provision('browsers',q)]);
  assert.equal(created,1);assert.equal(results.filter(r=>r.rental).length,1);assert.ok(results.some(r=>/cap/.test(r.reason)));
  const id=results.find(r=>r.rental).rental;
  await broker.bind(id,'m');
  const choice=await broker.decide({compute_pool:'browsers',owner:'user:alice',kind:'browser'},await desks.hosts());
  assert.equal(choice.selected,'m');assert.equal(choice.hourly,1);
  broker=createBroker({db:t.db,config,desks,adapters,now:()=>time});
  assert.match((await broker.provision('browsers',q)).reason,/cap/,'restart retains reservation');
  time+=3600000;await broker.tick();assert.equal(removed,1);
  let state=await broker.status();assert.equal(state.rentals[0].state,'releasing');assert.equal(state.budgets[0].committed_micros,'2000000');
  deleted=true;await broker.tick();state=await broker.status();assert.equal(state.rentals[0].state,'released');assert.equal(state.rentals[0].spent_micros,'1000000');
  assert.ok(state.journal.some(j=>j.event==='release.confirmed'));
  config.compute.providers.hetzner.monthly_cap='10';
  time=Date.UTC(2026,10,30,23,30);q.expires_at=time+60000;
  deleted=false;
  const cross=await broker.provision('browsers',q);
  desks.hosts=async()=>[{machine_id:'auto',name:cross.rental,trust:'community',online:true,free:4,max_browser_desks:4}];
  await broker.tick();assert.equal((await t.db.maybe('SELECT machine FROM run_compute_rentals WHERE id=$1',[cross.rental])).machine,null,'a community name cannot claim a rental');
  desks.hosts=async()=>[{machine_id:'auto',name:cross.rental,trust:'user-owned',online:true,free:4,max_browser_desks:4}];
  await broker.tick();assert.equal((await t.db.maybe('SELECT machine FROM run_compute_rentals WHERE id=$1',[cross.rental])).machine,'auto');
  const bound=await broker.decide({compute_pool:'browsers',owner:'user:alice',kind:'browser'},await desks.hosts());
  assert.equal(bound.hourly,1);assert.equal(bound.tier,'dedicated','rental retains provider tier and cost');
  const ownOnly=await broker.decide({compute_pool:'browsers',compute_strategy:'own',owner:'user:alice',kind:'browser'},await desks.hosts());
  assert.equal(ownOnly.selected,null,'rental is not an own-machine placement');
  time+=3600000;
  deleted=true;
  await broker.release(await t.db.maybe('SELECT * FROM run_compute_rentals WHERE id=$1',[cross.rental]));
  const charges=await t.db.many('SELECT * FROM run_compute_charges WHERE rental=$1 ORDER BY month',[cross.rental]);
  assert.deepEqual(charges.map(c=>[c.month,String(c.amount_micros)]),[['2026-11','500000'],['2026-12','500000']]);
  assert.equal((await broker.status()).budgets[0].spent_micros,'500000');
  q.expires_at=time+60000;deleted=false;
  config.compute.pools.browsers.min_warm=0;desks.hosts=async()=>[];
  const lowered=await broker.provision('browsers',q);
  config.compute.providers.hetzner.monthly_cap='2.25';
  await broker.tick();
  assert.equal((await t.db.maybe('SELECT state FROM run_compute_rentals WHERE id=$1',[lowered.rental])).state,'releasing','lowered cap includes already settled spend, not only live reservations');
  deleted=true;await broker.tick();config.compute.providers.hetzner.monthly_cap='10';
  q.expires_at=time+60000;uncertain=true;
  assert.match((await broker.provision('browsers',q)).reason,/unknown/);
  assert.match((await broker.provision('browsers',q)).reason,/unresolved/);
  time=Date.UTC(2027,0,1);q.expires_at=time+60000;
  assert.match((await broker.provision('browsers',q)).reason,/unresolved/,'month rollover cannot forget an unknown purchase');
  const privateChoice=await broker.decide({compute_pool:'browsers',compute_strategy:'private',owner:'user:alice',kind:'browser'},[{machine_id:'community',trust:'community',online:true,free:10}]);
  assert.equal(privateChoice.selected,null);
  console.log('compute cap, concurrent reservation, dry run, restart, release confirmation, unknown outcome and rollover: passed');
 } finally {await t.close();}
})().catch(e=>{console.error(e);process.exit(1);});
